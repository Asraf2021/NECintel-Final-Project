  let lang = "az";
  try { lang = localStorage.getItem("uce_lang") || "az"; } catch (e) { /* storage bağlı ola bilər */ }
  if (!DICT[lang]) lang = "az";
  const listeners = [];

  function t(key, params) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.az[key] || key;
    if (params) for (const k in params) s = s.split("{" + k + "}").join(params[k]);
    return s;
  }

  function apply(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    (root || document).querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    (root || document).querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    const meta = LANGS.find((l) => l.code === lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = meta ? meta.dir : "ltr";
  }

  function setLang(code) {
    if (!DICT[code]) return;
    lang = code;
    try { localStorage.setItem("uce_lang", code); } catch (e) { /* ignore */ }
    apply();
    renderSwitch();
    listeners.forEach((fn) => fn(code));
  }

  function renderSwitch() {
    document.querySelectorAll("[data-lang-switch]").forEach((box) => {
      box.innerHTML = "";
      LANGS.forEach((l) => {
        const b = document.createElement("button");
        b.type = "button";
        b.textContent = l.label;
        b.className = "lang-btn" + (l.code === lang ? " is-active" : "");
        b.setAttribute("aria-pressed", l.code === lang ? "true" : "false");
        b.addEventListener("click", () => setLang(l.code));
        box.appendChild(b);
      });
    });
  }

  window.I18N = { t, apply, setLang, onChange: (fn) => listeners.push(fn), get lang() { return lang; }, LANGS };
  document.addEventListener("DOMContentLoaded", () => { apply(); renderSwitch(); });
